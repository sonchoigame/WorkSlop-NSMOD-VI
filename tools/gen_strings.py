for en, id_, vi in T:
    if en in strings:
        continue
    strings[en] = {
        "localizations": {
            "en": unit(en),
            "id": unit(id_),
            "vi": unit(vi),
        }
    }

doc = {
    "sourceLanguage": "en",
    "strings": strings,
    "version": "1.0",
}
with open("WorkSlop/Localizable.xcstrings", "w") as f:
    json.dump(doc, f, ensure_ascii=False, indent=2)
    f.write("\n")
print("keys:", len(strings))
